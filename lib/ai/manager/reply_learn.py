#!/usr/bin/env python3
"""The keyboard AI reply button learning the user's style (docs/POWAI-ASSISTANT.md §3.9): text only, never screenshots.

Stored in the Keyboard AI app's own SpacetimeDB database (apps/keyboard-ai, `powos-keyboard-ai`, 127.0.0.1:3410 with
this user's ~/.config/spacetime/cli.toml identity), never in another app's tables:
  - `offer`   one row per answered draft request (reply_drafts.py): app, contact the model read off the screen, field
              hint, the variations, the press (session) it belongs to;
  - `outcome` what the keyboard reported for it (`powos manager --kb-outcome`, KeyboardAiProvider "outcome"): picked +
              the text actually committed (the field when sent or left) + edit distance, "more", or dismissed;
  - `profile` a short per-app / per-contact style summary, regenerated by the same claude path after every few new
              committed replies, in the outcome's process (the provider runs it in the background: off the request path).

Each draft request gets (context(), prompt_block()): the k past committed replies ranked by same app, same contact
(the likely one: the last contact seen in this app within LIKELY_MS) and lexical similarity to the voice note / field
text, plus the app's profile and up to MAX_CONTACT_PROFILES contact profiles - a few hundred words at most.
Embeddings: none yet (no local embedder on the phone); rank() is where one would score.

Nothing is learned for password / incognito fields (is_private) or an app whose learning is off (app_pref; the module
refuses too). The database missing or down never fails a draft: no learning that time.

  reply_learn.py --outcome      stdin: {"v":1, "rid", "action": picked|more|dismissed, "picked", "final", "sent",
                                "inputType", "imeOptions"} -> one JSON line {"ok": ..., "regenerated": [...]}
"""
from __future__ import annotations

import fcntl
import json
import math
import os
import random
import re
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request

_HERE = os.path.dirname(os.path.realpath(__file__))
for _d in (os.path.dirname(os.path.dirname(_HERE)), "/usr/lib/powos"):  # lib/ (repo) or the installed /usr/lib/powos
    if os.path.isdir(os.path.join(_d, "powos_py")) and _d not in sys.path:
        sys.path.append(_d)

DB = os.environ.get("POWOS_KB_DB", "powos-keyboard-ai")
SERVER = os.environ.get("POWOS_STDB", "http://127.0.0.1:3410")
HTTP_TIMEOUT = float(os.environ.get("POWOS_KB_TIMEOUT", "3"))
K = 5
EXAMPLE_LEN = 200
PROFILE_LEN = 400
MAX_CONTACT_PROFILES = 3
LIKELY_MS = 30 * 60_000
PROFILE_FIRST = 3       # committed replies before the first profile
PROFILE_EVERY_APP = 8   # new committed replies in the app before it's regenerated
PROFILE_EVERY_CONTACT = 5
PROFILE_FROM = 40       # the newest committed replies a profile is made from
ACTIONS = ("picked", "more", "dismissed")

PROFILE_SYSTEM = """You summarise how one person writes messages, from replies they actually sent (and the AI draft \
each started from, which they may have edited). Describe their style so a drafting model can imitate it: language(s), \
length, tone, formality, greetings/sign-offs, punctuation, capitalisation, emoji, recurring phrases, what they \
typically change in a draft. At most 5 short lines, no preamble, no quotes from private content beyond short \
characteristic phrases."""


class Unavailable(Exception):
    """The Keyboard AI database isn't there (not installed, SpacetimeDB down, no identity)."""


# ---------- the database ----------

def _token() -> str | None:
    try:
        from powos_py.common import token
    except ImportError:
        return None
    return token()


class Store:
    """The app's database over SpacetimeDB's HTTP API: sql() reads, call() runs a reducer."""

    def __init__(self, server: str = SERVER, db: str = DB, tok: str | None = None):
        self.server, self.db = server, db
        self.tok = tok if tok is not None else _token()

    def _post(self, path: str, body: bytes, ctype: str) -> str:
        if not self.tok:
            raise Unavailable("no SpacetimeDB identity")
        req = urllib.request.Request(f"{self.server}/v1/database/{self.db}/{path}", data=body, method="POST",
                                     headers={"Content-Type": ctype, "Authorization": f"Bearer {self.tok}"})
        try:
            with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as r:
                return r.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            raise Unavailable(f"{path}: HTTP {e.code} {e.read().decode('utf-8', 'replace')[:200]}") from None
        except (urllib.error.URLError, OSError) as e:
            raise Unavailable(str(e)) from None

    def sql(self, query: str) -> list[dict]:
        out = json.loads(self._post("sql", query.encode(), "text/plain"))
        res = out[0]
        names = [e["name"]["some"] for e in res["schema"]["elements"]]
        return [dict(zip(names, r)) for r in res["rows"]]

    def call(self, reducer: str, *args) -> None:
        self._post(f"call/{reducer}", json.dumps(list(args)).encode(), "application/json")


def q(s: str) -> str:
    """A SQL string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def origin() -> str:
    try:
        with open("/etc/hostname") as f:
            return f.read().strip()[:64] or socket.gethostname()[:64]
    except OSError:
        return socket.gethostname()[:64]


# ---------- privacy ----------

def is_private(input_type: int, ime_options: int) -> bool:
    """Password fields (text, web, visible, numeric PIN) and incognito ones (IME_FLAG_NO_PERSONALIZED_LEARNING): the
    keyboard's ReplyDrafts.isPrivateField, again here so nothing is learned even if a caller forgets."""
    cls, var = input_type & 0xF, input_type & 0xFF0
    if cls == 1 and var in (0x80, 0xE0, 0x90):
        return True
    if cls == 2 and var == 0x10:
        return True
    return bool(ime_options & 0x1000000)


# ---------- ranking ----------

_WORD = re.compile(r"\w+", re.UNICODE)


def tokens(s: str) -> set[str]:
    return {w for w in _WORD.findall((s or "").lower()) if len(w) > 1 or not w.isascii()}


def jaccard(a: set[str], b: set[str]) -> float:
    return len(a & b) / len(a | b) if a and b else 0.0


def committed(rows: list[dict]) -> list[dict]:
    """Rows whose outcome was a pick with a final text: what the user actually sent."""
    return [r for r in rows if r.get("action") == "picked" and (r.get("final_text") or "").strip()]


def likely_contact(rows: list[dict], app: str, now_ms: int) -> str:
    """The contact of this app's newest request within LIKELY_MS (the same conversation, most likely), else ""."""
    recent = [r for r in rows if r.get("app") == app and r.get("contact") and now_ms - int(r.get("at") or 0) < LIKELY_MS]
    return max(recent, key=lambda r: int(r.get("at") or 0))["contact"] if recent else ""


def score(row: dict, app: str, contact: str, query: set[str], now_ms: int) -> float:
    s = 2.0 if row.get("app") == app else 0.0
    if contact and (row.get("contact") or "").lower() == contact.lower():
        s += 2.0
    s += 1.5 * jaccard(query, tokens((row.get("final_text") or "") + " " + (row.get("hint") or "")))
    age_days = max(0, now_ms - int(row.get("at") or 0)) / 86_400_000
    s += 0.5 * math.exp(-age_days / 30)
    return s


def rank(rows: list[dict], app: str, contact: str, query: str, now_ms: int, k: int = K) -> list[dict]:
    """The k committed replies most like this request: same app, same contact, words shared with the voice note /
    field text, then newer. Identical texts once."""
    qt = tokens(query)
    seen, out = set(), []
    for r in sorted(committed(rows), key=lambda r: (-score(r, app, contact, qt, now_ms), -int(r.get("at") or 0))):
        key = r["final_text"].strip().lower()
        if key in seen:
            continue
        seen.add(key)
        out.append(r)
        if len(out) >= k:
            break
    return out


# ---------- the request side ----------

def learning_on(store: Store, app: str) -> bool:
    return not any(not p.get("learn", True) for p in store.sql(f"SELECT * FROM app_pref WHERE app = {q(app)}"))


def context(req: dict, store: Store | None = None, now_ms: int | None = None) -> dict:
    """What this request learns from and records into: {"learn", "examples", "profiles", "contact"}; learn False (and
    nothing else) for a private field, an app switched off, no app, or no database."""
    off = {"learn": False, "examples": [], "profiles": [], "contact": ""}
    if not req.get("app") or is_private(req.get("inputType", 0), req.get("imeOptions", 0)):
        return off
    try:
        store = store or Store()
        if not learning_on(store, req["app"]):
            return off
        rows = store.sql("SELECT * FROM reply WHERE action = 'picked'")
        recent = store.sql(f"SELECT * FROM reply WHERE app = {q(req['app'])}")
        profiles = store.sql(f"SELECT * FROM profile WHERE app = {q(req['app'])}")
    except (Unavailable, ValueError, KeyError, IndexError) as e:
        print(f"reply_learn: no learning this time: {e}", file=sys.stderr)
        return off
    now_ms = now_ms if now_ms is not None else int(time.time() * 1000)
    contact = likely_contact(recent, req["app"], now_ms)
    examples = rank(rows, req["app"], contact, " ".join((req.get("transcript", ""), req.get("text", ""))), now_ms)
    return {"learn": True, "examples": examples, "profiles": pick_profiles(profiles, contact), "contact": contact}


def pick_profiles(profiles: list[dict], contact: str) -> list[dict]:
    """The app's profile, then the likely contact's, then the newest other contacts' (MAX_CONTACT_PROFILES in all)."""
    app_p = [p for p in profiles if not p.get("contact")]
    people = sorted((p for p in profiles if p.get("contact")),
                    key=lambda p: (p["contact"].lower() != contact.lower(), -int(p.get("at") or 0)))
    return app_p[:1] + people[:MAX_CONTACT_PROFILES]


def _short(s: str, n: int) -> str:
    s = " ".join((s or "").split())
    return s if len(s) <= n else s[: n - 1] + "…"


def prompt_block(ctx: dict) -> str:
    """The learned part of the draft prompt ("" when there is nothing): profiles, then examples. Small on purpose."""
    lines = []
    for p in ctx.get("profiles") or []:
        who = f"with {p['contact']}" if p.get("contact") else "in this app"
        lines.append(f"How they write {who}: {_short(p.get('text', ''), PROFILE_LEN)}")
    ex = ctx.get("examples") or []
    if ex:
        lines.append("Replies they actually sent before (most similar first) - match their style, don't copy them:")
        for r in ex:
            to = f" to {r['contact']}" if r.get("contact") else ""
            lines.append(f"- ({r.get('app', '')}{to}) {json.dumps(_short(r['final_text'], EXAMPLE_LEN), ensure_ascii=False)}")
    if ctx.get("contact"):
        lines.append(f"(The last conversation in this app was with {ctx['contact']}.)")
    return "\n".join(lines)


def new_rid(host: str) -> str:
    return f"{host}-{int(time.time() * 1000)}-{random.randrange(16 ** 4):04x}"


def record_offer(req: dict, variations: list[str], contact: str, store: Store | None = None) -> str | None:
    """The answered request as an `offer` row; its id (the "rid" the keyboard reports outcomes with), None when it
    couldn't be stored (the keyboard then reports nothing)."""
    host = origin()
    rid = new_rid(host)
    row = {"id": rid, "session": (req.get("session") or rid)[:100], "app": req["app"], "contact": contact[:100],
           "hint": req.get("hint", "")[:200], "drafts": variations, "origin": host}
    try:
        (store or Store()).call("offer", json.dumps(row, ensure_ascii=False))
    except Unavailable as e:
        print(f"reply_learn: offer not stored: {e}", file=sys.stderr)
        return None
    return rid


# ---------- the outcome side ----------

def edit_distance(a: str, b: str, cap: int = 1000) -> float:
    """Levenshtein distance a -> b over characters, normalised by the longer one: 0 = unchanged, 1 = all different."""
    a, b = (a or "")[:cap], (b or "")[:cap]
    if a == b:
        return 0.0
    if not a or not b:
        return 1.0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return round(prev[-1] / max(len(a), len(b)), 4)


def parse_outcome(raw: str) -> dict:
    """The keyboard's report, checked: ValueError for anything that isn't one."""
    o = json.loads(raw)
    if not isinstance(o, dict) or o.get("v", 1) != 1:
        raise ValueError("not a v1 outcome")
    rid, action = o.get("rid"), o.get("action")
    if not isinstance(rid, str) or not rid or len(rid) > 100 or action not in ACTIONS:
        raise ValueError("rid / action")
    return {"rid": rid, "action": action, "picked": int(o.get("picked", -1)), "final": str(o.get("final") or "")[:2000],
            "sent": bool(o.get("sent")), "inputType": int(o.get("inputType", 0)), "imeOptions": int(o.get("imeOptions", 0))}


def outcome_row(o: dict, offered: dict) -> dict:
    """The `outcome` reducer's argument: the edit distance from the picked draft to the committed text."""
    edit = -1.0
    if o["action"] == "picked":
        try:
            drafts = json.loads(offered.get("drafts") or "[]")
        except ValueError:
            drafts = []
        if 0 <= o["picked"] < len(drafts) and o["final"].strip():
            edit = edit_distance(drafts[o["picked"]].strip(), o["final"].strip())
    return {"id": o["rid"], "action": o["action"], "picked": o["picked"], "final_text": o["final"], "edit": edit,
            "sent": o["sent"]}


def profile_due(n_total: int, n_since: int, has_profile: bool, every: int) -> bool:
    """Regenerate a profile: the first once PROFILE_FIRST replies were committed, then after every [every] new ones."""
    return n_since >= every if has_profile else n_total >= PROFILE_FIRST


def due_profiles(rows: list[dict], profiles: list[dict], app: str, contact: str) -> list[str]:
    """Which profiles of [app] to regenerate after a pick: "" (the app's) and/or [contact]."""
    done = committed([r for r in rows if r.get("app") == app])
    by_id = {(p.get("contact") or ""): p for p in profiles if p.get("app") == app}
    out = []
    for who, every in [("", PROFILE_EVERY_APP)] + ([(contact, PROFILE_EVERY_CONTACT)] if contact else []):
        mine = [r for r in done if not who or (r.get("contact") or "").lower() == who.lower()]
        p = by_id.get(who)
        since = sum(1 for r in mine if int(r.get("done_at") or r.get("at") or 0) > int(p.get("at") or 0)) if p else 0
        if profile_due(len(mine), since, p is not None, every):
            out.append(who)
    return out


def profile_prompt(rows: list[dict], app: str, contact: str) -> tuple[str, int]:
    """The profile model's input (the newest PROFILE_FROM committed replies, with the draft each began as when
    edited) and how many replies it holds."""
    mine = [r for r in committed(rows) if r.get("app") == app
            and (not contact or (r.get("contact") or "").lower() == contact.lower())]
    mine = sorted(mine, key=lambda r: -int(r.get("at") or 0))[:PROFILE_FROM]
    lines = [f"App: {app}" + (f", writing to {contact}" if contact else " (all conversations)")]
    for r in mine:
        try:
            drafts = json.loads(r.get("drafts") or "[]")
            draft = drafts[r["picked"]] if 0 <= int(r.get("picked", -1)) < len(drafts) else ""
        except (ValueError, TypeError):
            draft = ""
        sent = _short(r["final_text"], 300)
        lines.append(f"- sent: {json.dumps(sent, ensure_ascii=False)}"
                     + (f" (draft was {json.dumps(_short(draft, 300), ensure_ascii=False)})" if draft and draft.strip() != r["final_text"].strip() else ""))
    return "\n".join(lines), len(mine)


def run_profile_model(prompt: str) -> str:
    """One text-only claude turn (reply_drafts' command and sign-in, another system prompt): the summary, "" on failure."""
    import reply_drafts as rd
    cmd = rd.claude_cmd()
    cmd[cmd.index("--system-prompt") + 1] = PROFILE_SYSTEM
    msg = {"type": "user", "message": {"role": "user", "content": [{"type": "text", "text": prompt}]}}
    try:
        p = subprocess.run(cmd, input=json.dumps(msg) + "\n", capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=rd.TIMEOUT_S)
    except (subprocess.TimeoutExpired, OSError) as e:
        print(f"reply_learn: profile model: {e}", file=sys.stderr)
        return ""
    for line in p.stdout.splitlines():
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        if ev.get("type") == "result" and not ev.get("is_error"):
            return (ev.get("result") or "").strip()[:1200]
    return ""


def _lock():
    """One profile regeneration at a time on this host (None: another is running - skip, the next pick retries)."""
    d = os.environ.get("XDG_RUNTIME_DIR") or os.path.expanduser("~/.cache")
    os.makedirs(d, exist_ok=True)
    f = open(os.path.join(d, "powos-keyboard-ai.lock"), "w")
    try:
        fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        f.close()
        return None
    return f


def regenerate(store: Store, app: str, contact: str) -> list[str]:
    """Regenerates the due profiles of [app] (and [contact]); the ones written."""
    rows = store.sql(f"SELECT * FROM reply WHERE app = {q(app)}")
    profiles = store.sql(f"SELECT * FROM profile WHERE app = {q(app)}")
    due = due_profiles(rows, profiles, app, contact)
    if not due:
        return []
    lock = _lock()
    if lock is None:
        return []
    written = []
    with lock:
        for who in due:
            prompt, n = profile_prompt(rows, app, who)
            text = run_profile_model(prompt)
            if text:
                store.call("profile_set", json.dumps({"app": app, "contact": who, "text": text, "outcomes": n,
                                                      "origin": origin()}, ensure_ascii=False))
                written.append(who or "(app)")
    return written


def handle_outcome(o: dict, store: Store | None = None, regen=regenerate) -> dict:
    """Records one keyboard report; after a pick, regenerates the profiles that are due (in this process: the provider
    runs it in the background, never on a draft's path)."""
    if is_private(o["inputType"], o["imeOptions"]):
        return {"ok": True, "recorded": False, "why": "private field"}
    store = store or Store()
    rows = store.sql(f"SELECT * FROM reply WHERE id = {q(o['rid'])}")
    if not rows:
        return {"ok": True, "recorded": False, "why": "no such offer (learning off, cleared or expired)"}
    offered = rows[0]
    if not learning_on(store, offered["app"]):
        return {"ok": True, "recorded": False, "why": "learning is off for this app"}
    row = outcome_row(o, offered)
    store.call("outcome", json.dumps(row, ensure_ascii=False))
    out = {"ok": True, "recorded": True, "edit": row["edit"]}
    if o["action"] == "picked":
        out["regenerated"] = regen(store, offered["app"], offered.get("contact") or "")
    return out


def main(argv: list[str]) -> int:
    if argv[1:2] != ["--outcome"]:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        o = parse_outcome(sys.stdin.read())
    except (ValueError, TypeError) as e:
        print(json.dumps({"ok": False, "error": "bad-request", "why": str(e)}))
        return 2
    try:
        out = handle_outcome(o)
    except Unavailable as e:
        out = {"ok": False, "error": "unavailable", "why": str(e)}
    print(json.dumps(out, ensure_ascii=False))
    return 0 if out["ok"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
